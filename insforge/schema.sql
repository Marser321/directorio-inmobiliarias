create or replace function public.publish_prospect_properties_realtime()
returns trigger
language plpgsql
security definer
as $$
declare
  v_agency_id bigint;
begin
  v_agency_id := coalesce(new.agency_id, old.agency_id);

  perform realtime.publish(
    'prospect_properties:' || v_agency_id::text,
    tg_op || '_prospect_properties',
    jsonb_build_object(
      'op', tg_op,
      'agency_id', v_agency_id,
      'new', case when tg_op = 'DELETE' then null else to_jsonb(new) end,
      'old', case when tg_op = 'INSERT' then null else to_jsonb(old) end
    )
  );

  return coalesce(new, old);
end;
$$;

drop trigger if exists prospect_properties_realtime_trigger on public.prospect_properties;
create trigger prospect_properties_realtime_trigger
after insert or update or delete on public.prospect_properties
for each row
execute function public.publish_prospect_properties_realtime();

