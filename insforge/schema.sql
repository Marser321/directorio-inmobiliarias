create or replace function public.get_my_agency_id()
returns bigint
language sql
stable
security definer
as $$
  select agency_id from public.agency_memberships where user_id = auth.uid() limit 1;
$$;

create or replace function public.get_coverage_gaps(days_back int default 30)
returns table (
  neighborhood text,
  zone text,
  property_category text,
  property_count bigint,
  priority text
)
language sql
stable
security definer
as $$
  select
    coalesce(city, 'Unknown') as neighborhood,
    coalesce(city, 'Unknown') as zone,
    coalesce(features->>'type', 'unknown') as property_category,
    count(*)::bigint as property_count,
    case
      when count(*) = 0 then 'urgent'
      when count(*) < 3 then 'high'
      else 'medium'
    end as priority
  from public.properties
  where created_at > now() - (days_back || ' days')::interval
    and agency_id = public.get_my_agency_id()
  group by 1, 2, 3
  order by property_count asc;
$$;

create or replace function public.get_innovation_suggestions(days_back int default 7)
returns table (
  query text,
  search_count bigint,
  suggested_category text
)
language sql
stable
security definer
as $$
  select
    us.query,
    count(*)::bigint as search_count,
    case
      when us.query ilike '%terreno%' then 'terreno'
      when us.query ilike '%local%' or us.query ilike '%comercial%' then 'local_comercial'
      when us.query ilike '%oficina%' then 'oficina'
      when us.query ilike '%campo%' or us.query ilike '%chacra%' then 'campo'
      else 'nueva_categoria'
    end as suggested_category
  from public.user_searches us
  where us.created_at > now() - (days_back || ' days')::interval
    and us.results_count = 0
    and (us.agency_id is null or us.agency_id = public.get_my_agency_id())
  group by us.query
  having count(*) >= 3
  order by search_count desc
  limit 10;
$$;

